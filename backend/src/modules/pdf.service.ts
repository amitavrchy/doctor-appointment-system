import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
@Injectable()
export class PdfService {
  async render(title:string,lines:string[]):Promise<Buffer> {
    return new Promise(resolve=>{
      const doc=new PDFDocument({size:'A4',margin:56});const chunks:Buffer[]=[];
      doc.on('data',chunk=>chunks.push(chunk));doc.on('end',()=>resolve(Buffer.concat(chunks)));
      doc.fillColor('#0f766e').fontSize(26).text('careflow');doc.moveDown().fillColor('#172e33').fontSize(20).text(title);doc.moveDown();
      for(const line of lines){doc.fontSize(12).fillColor('#334b50').text(line,{lineGap:6});doc.moveDown(0.4);}
      doc.moveDown().fontSize(10).fillColor('#607779').text('Generated by Careflow. Verify the status before use.');doc.end();
    });
  }
}
