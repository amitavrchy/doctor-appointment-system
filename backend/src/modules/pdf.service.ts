import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import QRCode from 'qrcode';
import type { Medication } from './clinical.service';
@Injectable()
export class PdfService {
  async render(title: string, lines: string[], verificationUrl?: string): Promise<Buffer> {
    const qr = verificationUrl
      ? await QRCode.toBuffer(verificationUrl, { width: 130, margin: 1 })
      : null;
    return new Promise((resolve) => {
      const doc = new PDFDocument({ size: 'A4', margin: 56 });
      const chunks: Buffer[] = [];
      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.fillColor('#0f766e').fontSize(26).text('careflow');
      doc.moveDown().fillColor('#172e33').fontSize(20).text(title);
      doc.moveDown();
      for (const line of lines) {
        doc.fontSize(12).fillColor('#334b50').text(line, { lineGap: 6 });
        doc.moveDown(0.4);
      }
      if (qr) {
        doc.moveDown();
        doc.image(qr, { width: 100 });
      }
      doc
        .moveDown()
        .fontSize(10)
        .fillColor('#607779')
        .text('Generated by Careflow. Verify the status before use.');
      doc.end();
    });
  }
  prescription(p: {
    id: string;
    status: string;
    items: unknown;
    signedAt: Date | null;
    signature: string | null;
    verificationCode: string;
    appointment: {
      patient: { fullName: string };
      doctor: { user: { fullName: string }; licenseNumber: string };
      clinic: { name: string };
    };
  }) {
    const url = `${process.env.APP_URL}/verify?code=${p.verificationCode}`;
    return this.render(
      'Prescription',
      [
        `Status: ${p.status}`,
        `Patient: ${p.appointment.patient.fullName}`,
        `Doctor: ${p.appointment.doctor.user.fullName} | ${p.appointment.doctor.licenseNumber}`,
        `Clinic: ${p.appointment.clinic.name}`,
        `Signed: ${p.signedAt?.toISOString() || 'Not signed'}`,
        ...(p.items as Medication[]).map(
          (m) =>
            `${m.name} | ${m.dosage} | ${m.frequency} | ${m.duration} | ${m.route}\n${m.instructions}`,
        ),
        `Verify: ${url}`,
        `Signature (demonstration HMAC): ${p.signature}`,
      ],
      url,
    );
  }
}
